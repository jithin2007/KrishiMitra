-- ---------------------------------------------------------------------
-- 1. SEQUENCES
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_FARMER_ID          START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_FARM_ID            START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_SOIL_ID            START WITH 1 INCREMENT BY 1 NOCACHE;
